// TypeScript types of the inputs of addcctl's operations, generated from
// their JSON Schemas (`addcctl schema`, core/addcctl/operations.py).
//
//   node scripts/addcctl-types.mjs           write src/lib/addcctl-schema.ts
//   node scripts/addcctl-types.mjs --check   fail when it is not up to date (CI)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const OUTPUT = "src/lib/addcctl-schema.ts";

// "share rename-principal" -> "ShareRenamePrincipalInput"
export function typeName(operation) {
    return operation.split(/[\s-]+/).map(w => w[0].toUpperCase() + w.slice(1)).join("") + "Input";
}

function comment(text, indent) {
    return text ? `${indent}/** ${text.replace(/\*\//g, "*\\/")} */\n` : "";
}

// One JSON Schema (the subset addcctl uses) as a TypeScript type
export function tsType(schema, indent = "") {
    const types = schema.type === undefined ? [] : [].concat(schema.type);
    const parts = types.map(t => {
        switch (t) {
            case "null": return "null";
            case "boolean": return "boolean";
            case "integer": return "number";
            case "string": return schema.enum ? schema.enum.map(v => JSON.stringify(v)).join(" | ") : "string";
            case "array": return `${wrap(tsType(schema.items ?? {}, indent))}[]`;
            case "object": return objectType(schema, indent);
            default: throw new Error(`unsupported type ${t}`);
        }
    });
    return parts.length ? parts.join(" | ") : "unknown";
}

function wrap(type) {
    return type.includes(" | ") ? `(${type})` : type;
}

function objectType(schema, indent) {
    const props = Object.entries(schema.properties ?? {});
    if (props.length === 0) return "Record<string, never>";
    const required = new Set(schema.required ?? []);
    const inner = indent + "    ";
    const lines = props.map(([key, value]) =>
        comment(value.description, inner) +
        `${inner}${/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key)}${required.has(key) ? "" : "?"}: ${tsType(value, inner)};\n`);
    return `{\n${lines.join("")}${indent}}`;
}

export function generate(schemas) {
    const names = Object.keys(schemas).sort();
    let out = "// Generated by scripts/addcctl-types.mjs from `addcctl schema`: do not edit.\n" +
        "// The inputs of addcctl's operations (core/addcctl/operations.py).\n";
    for (const name of names) {
        out += `\n${comment(`${name}: ${schemas[name].description}`, "")}export type ${typeName(name)} = ${tsType(schemas[name].input)};\n`;
    }
    out += "\nexport interface AddcctlInputs {\n" +
        names.map(n => `    ${JSON.stringify(n)}: ${typeName(n)};\n`).join("") + "}\n";
    return out;
}

function main(args) {
    const schemas = JSON.parse(execFileSync("python3", ["-m", "addcctl", "schema"], { cwd: "core", encoding: "utf8" }));
    const text = generate(schemas);
    if (args.includes("--check")) {
        let current = "";
        try { current = readFileSync(OUTPUT, "utf8"); } catch { /* missing */ }
        if (current !== text) {
            console.error(`${OUTPUT} is not up to date: run make schema`);
            process.exit(1);
        }
        return;
    }
    writeFileSync(OUTPUT, text);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
